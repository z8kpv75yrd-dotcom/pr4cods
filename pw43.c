#include <stdio.h>

int main(void){
    int N;
    int i = 1;
    int a = 10;
    printf("Введи кол-во элементов: ");
    if (scanf("%d", &N)!=1 || N<=0){
        printf("Введи положительное число!\n");
        return 1;
    }
    // a-- (постфиксный) сначала дает старое значение a и только потом
    // уменьшает его. --a (префиксный) наоборот: сначала уменьшает,
    // потом дает новое значение.
    // Тут порядок важен: сначала выводим a, потом уменьшаем,
    // иначе первым числом будет 9, а не 10
    while (i<=N){
        printf("%d ", a);
        a--;
        i++;
    }
    printf("\n");
    return 0;
}